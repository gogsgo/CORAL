#!/usr/bin/env node
/**
 * CORAL CLI.
 *
 * Eight verbs, one reef. Every command opens the same object graph (runtime.ts)
 * so `scan` and `trade` can never disagree about limits or memory state.
 */
import { Command, Option } from "commander";
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { formatDistanceToNow } from "date-fns";

import { evolve, type CoralEvent } from "@coral/core";
import { HOSTS, ROBINHOOD, applyToHost, detect, resolveHost } from "@coral/mcp-connectors";
import { serveCoral } from "@coral/mcp-connectors/server";

import { boot, parseSymbols } from "./runtime.js";
import { banner, c, fail, heading, keyValue, note, ok, riskBar, table, warn } from "./ui.js";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")) as { version: string };

const program = new Command();

program
  .name("coral")
  .description("CORAL — a self-evolving trading agent that grows a reef of memory.")
  .version(pkg.version, "-v, --version")
  .addOption(new Option("-m, --mode <mode>", "paper | live").choices(["paper", "live"]).default(undefined))
  .showHelpAfterError("(run `coral --help` for the full surface)");

// ── init ──────────────────────────────────────────────────────────────────

program
  .command("init")
  .description("spawn a reef: create .coral/, write .env, print next steps")
  .option("-f, --force", "overwrite an existing .env")
  .option("--symbols <list>", "default watchlist", "AAPL,NVDA,SPY,MSFT,TSLA")
  .action((opts: { force?: boolean; symbols: string }) => {
    banner();
    const home = process.env.CORAL_HOME ?? join(process.cwd(), ".coral");
    mkdirSync(home, { recursive: true });

    const rt = boot({ home });
    const snap = rt.memory.snapshot();
    ok(`reef spawned at ${c.bold(rt.config.dbPath)}`);
    ok(`generation ${snap.generation} · ${snap.polyps} polyps`);

    const envPath = join(home, "..", ".env");
    if (!existsSync(envPath) || opts.force) {
      const template = [
        "# CORAL — generated by `coral init`",
        "CORAL_MODE=paper",
        "CORAL_HOME=",
        "CORAL_LLM=anthropic",
        "ANTHROPIC_API_KEY=",
        "ROBINHOOD_MCP_TOKEN=",
        `ROBINHOOD_CHAIN_RPC=${ROBINHOOD.chainMainnet}`,
        "",
        `# watchlist: ${opts.symbols}`,
      ].join("\n");
      writeFileSync(envPath, `${template}\n`, "utf8");
      ok(`wrote ${envPath} — fill in a model key to switch from heuristic to LLM reasoning`);
    } else {
      warn(`${envPath} already exists (use --force to overwrite)`);
    }

    console.log();
    keyValue([
      ["mode", rt.config.mode === "paper" ? c.teal("paper") : c.red("LIVE")],
      ["reasoner", rt.engine.reasoner === "llm" ? c.green(rt.config.model) : c.dim("heuristic (no key set)")],
      ["chain", `${rt.config.robinhood.chainRpc} (id ${rt.config.robinhood.chainId})`],
      ["limits", `$${rt.risk.limits.maxOrderUsd}/order · $${rt.risk.limits.maxDeployedUsd} deployed · min conf ${rt.risk.limits.minConfidence}`],
    ]);

    console.log(`\n  next: ${c.bold("coral connect --all")}   then   ${c.bold(`coral scan ${opts.symbols.split(",")[0]}`)}\n`);
    rt.close();
  });

// ── connect ───────────────────────────────────────────────────────────────

program
  .command("connect")
  .description("register an MCP server in an agent host (claude-code, codex, cursor, gemini, grok, claude-desktop)")
  .argument("[host]", "host id, or omit with --all")
  .option("--all", "every host detected on this machine")
  .option("--self", "register CORAL's own MCP server instead of Robinhood's")
  .option("--dry-run", "print the config that would be written, touch nothing")
  .option("--token <token>", "bearer token for the remote server")
  .option("--name <name>", "server name to write", "robinhood-trading")
  .action((host: string | undefined, opts: { all?: boolean; self?: boolean; dryRun?: boolean; token?: string; name: string }) => {
    const spec = opts.self
      ? {
          // CORAL's own server runs over stdio; we register the command, not a URL.
          url: "",
          token: null,
          headers: {},
        }
      : {
          url: ROBINHOOD.tradingMcp,
          token: opts.token ?? process.env.ROBINHOOD_MCP_TOKEN ?? null,
          headers: {},
        };

    const targets = opts.all || !host ? HOSTS : [resolveHost(host)];
    if (!opts.all && !host) {
      warn("no host given and --all not set — showing what is available:");
      table(
        ["host", "config path", "exists"],
        HOSTS.map((h) => [h.id, h.configPath(), existsSync(h.configPath()) ? "yes" : "no"]),
      );
      console.log(`\n  run ${c.bold("coral connect --all")} to write every host, or ${c.bold("coral connect cursor")} for one.\n`);
      return;
    }

    heading(opts.self ? "CORAL → your agents (as an MCP server)" : "Robinhood Trading MCP → your agents");
    if (opts.self) {
      note("note", "CORAL's server uses stdio. Register it with the command below, not with this writer.");
      console.log(`\n  ${c.bold("claude mcp add coral -- coral serve")}`);
      console.log(`  ${c.bold("codex mcp add coral -- pnpm --filter @coral/cli exec tsx src/index.ts serve")}`);
      console.log(`  ${c.dim("or add to any host's config:")}  { "command": "npx", "args": ["-y","@coral/cli","serve"] }\n`);
      return;
    }

    for (const target of targets) {
      const result = applyToHost(target, opts.name, spec, { dryRun: opts.dryRun ?? false });
      if (result.dryRun) {
        console.log(`  ${c.dim(target.id)} ${c.dim("→ " + result.path)}`);
        console.log(c.dim(JSON.stringify(result.content, null, 2).split("\n").map((l) => "    " + l).join("\n")));
      } else if (!result.changed) {
        note(target.label, c.dim(result.reason ?? "unchanged"));
      } else {
        ok(`${target.label} → ${result.path}`);
        if (result.backup) note("backup", c.dim(result.backup));
        if (target.restartHint) note("next", c.dim(target.restartHint));
      }
    }
    console.log();
  });

// ── status ────────────────────────────────────────────────────────────────

program
  .command("status")
  .description("reef health: memory, generation, limits, connectivity")
  .option("--skills", "list registered skills and their live strength")
  .option("--json", "machine-readable output")
  .action(async (opts: { skills?: boolean; json?: boolean }) => {
    const rt = boot(program.opts().mode ? { mode: program.opts().mode } : {});
    const snap = rt.memory.snapshot();
    const deployed = rt.memory.deployedCapital();
    const positions = rt.memory.openPositions();

    if (opts.json) {
      console.log(JSON.stringify({ config: { ...rt.config, robinhood: { ...rt.config.robinhood, mcpToken: rt.config.robinhood.mcpToken ? "set" : null } }, snapshot: { ...snap, zones: snap.zones.slice(0, 20) }, deployed, positions, reasoner: rt.engine.reasoner }, null, 2));
      rt.close();
      return;
    }

    banner();
    const age = formatDistanceToNow(new Date(snap.spawnedAt), { addSuffix: false });

    heading(`Reef · generation ${snap.generation}`);
    keyValue([
      ["age", age],
      ["polyps", `${snap.polyps}  ${c.dim(`(${Object.entries(snap.byKind).filter(([, n]) => n > 0).map(([k, n]) => `${k} ${n}`).join(" · ") || "none yet"})`)}`],
      ["settled", `${snap.wins}W / ${snap.losses}L${snap.pending ? c.dim(` · ${snap.pending} pending`) : ""}`],
      ["win rate", snap.winRate === 0 ? c.dim("n/a") : `${(snap.winRate * 100).toFixed(1)}%`],
      ["realised", `${snap.pnl >= 0 ? c.green("$" + snap.pnl.toFixed(2)) : c.red("$" + snap.pnl.toFixed(2))}`],
      ["last activity", snap.lastActivity ? formatDistanceToNow(new Date(snap.lastActivity), { addSuffix: true }) : c.dim("never")],
    ]);

    heading("Limits · hard-coded, not prompted");
    keyValue([
      ["mode", rt.config.mode === "paper" ? c.teal("paper (no real money)") : c.red("LIVE")],
      ["reasoner", rt.engine.reasoner === "llm" ? `${rt.config.llm} / ${rt.config.model}` : c.dim("heuristic fallback (set an API key to reason with a model)")],
      ["per order", `$${rt.risk.limits.maxOrderUsd}`],
      ["deployed", `${riskBar(deployed, rt.risk.limits.maxDeployedUsd, 18)}  $${deployed.toFixed(2)} / $${rt.risk.limits.maxDeployedUsd}`],
      ["max position", `${(rt.risk.limits.maxPositionPct * 100).toFixed(0)}% of deployed`],
      ["min confidence", rt.risk.limits.minConfidence.toFixed(2)],
      ["circuit breaker", `${rt.risk.limits.maxConsecutiveLosses} losses · -$${rt.risk.limits.maxDailyLossUsd}/day`],
      ["live trading", rt.risk.limits.allowLive ? c.amber("allowed by limits") : c.dim("blocked by limits.allowLive")],
    ]);

    if (positions.length) {
      heading("Open positions");
      table(
        ["symbol", "qty", "cost", "avg"],
        positions.map((p) => [p.symbol, p.qty.toFixed(4), `$${p.cost.toFixed(2)}`, `$${(p.cost / Math.max(p.qty, 1e-9)).toFixed(2)}`]),
      );
    }

    if (snap.zones.length) {
      heading("Zones · where the reef is strong");
      table(
        ["zone", "polyps", "W", "L", "strength"],
        snap.zones.slice(0, 10).map((z) => [
          z.name,
          z.polyps,
          z.wins,
          z.losses,
          z.wins + z.losses === 0 ? c.dim("untested") : `${(z.strength * 100).toFixed(0)}%`,
        ]),
      );
    }

    if (opts.skills) {
      heading("Skills · live strength");
      table(
        ["skill", "strength", "available", "what it does"],
        rt.router.list().map((s) => [
          s.name,
          `${(s.strength * 100).toFixed(0)}%`,
          s.available && !s.available() ? c.dim("no") : "yes",
          s.description.slice(0, 52),
        ]),
      );
    }

    heading("Connectivity");
    const mcpProbe = await rt.mcp.connect().then(() => true).catch(() => false);
    const chain = await rt.chain.info();
    keyValue([
      ["robinhood mcp", mcpProbe ? c.green(`connected · ${rt.mcp.listTools().length} tools`) : c.dim(rt.config.robinhood.mcpToken ? "token set, connection failed" : "no token set")],
      ["robinhood chain", chain.ok ? c.green(`id ${chain.chainId} · head ${chain.blockNumber}`) : c.red(`unreachable (${rt.config.robinhood.chainRpc})`)],
      ["market data", rt.source.name === "synthetic" ? c.amber("synthetic (no MCP token)") : c.green("robinhood-mcp")],
    ]);

    const hosts = detect().filter((h) => h.exists);
    if (hosts.length) {
      heading("Agent hosts detected");
      table(["host", "configured servers"], hosts.map((h) => [h.host.id, h.has.join(", ") || c.dim("none")]));
    }
    console.log();
    rt.close();
  });

// ── scan ──────────────────────────────────────────────────────────────────

const streamEvent = (e: CoralEvent): void => {
  switch (e.type) {
    case "phase":
      console.log(c.dim(`\n  ▸ ${e.phase}${e.note ? " · " + e.note : ""}`));
      break;
    case "observation":
      console.log(
        `    ${c.bold(e.observation.symbol.padEnd(6))} $${e.observation.price.toFixed(2).padStart(9)}  ` +
          `24h ${((e.observation.change24h >= 0 ? c.green("+") : c.red("")) + (e.observation.change24h * 100).toFixed(2) + "%").padEnd(22)} ` +
          `rsi ${e.observation.rsi14.toFixed(0).padStart(3)}  ${c.dim(e.observation.source)}`,
      );
      break;
    case "recall":
      console.log(`    ${c.dim("recall")} ${e.symbol}: ${e.hits} polyp(s)${e.top ? c.dim(" — " + e.top) : ""}`);
      break;
    case "decision": {
      const colour = e.decision.action === "buy" ? c.green : e.decision.action === "sell" ? c.red : c.dim;
      console.log(`    ${c.dim("decide")} ${e.decision.symbol.padEnd(6)} ${colour(e.decision.action.toUpperCase().padEnd(5))} conf ${e.decision.confidence.toFixed(2)}`);
      break;
    }
    case "gate":
      console.log(
        `    ${e.allowed ? c.green("gate ✓") : c.red("gate ✗")} ${e.symbol}` +
          (e.reasons.length ? c.dim(" — " + e.reasons.slice(0, 2).join("; ")) : ""),
      );
      break;
    case "execution":
      if (e.execution.status === "filled") {
        console.log(`    ${c.green("fill")} ${e.execution.action} ${e.execution.symbol} $${e.execution.notional.toFixed(2)} @ $${e.execution.price.toFixed(2)}`);
      } else if (e.execution.status === "rejected") {
        console.log(`    ${c.red("reject")} ${e.execution.symbol}${e.execution.reasons.length ? c.dim(" — " + e.execution.reasons[0]) : ""}`);
      }
      break;
    case "settled":
      console.log(`    ${c.dim("settle")} ${e.symbol} → ${e.outcome} (${e.pnl >= 0 ? "+" : ""}${e.pnl.toFixed(2)})`);
      break;
    case "done":
      break;
  }
};

program
  .command("scan")
  .description("observe + reason + gate, without placing anything")
  .argument("[symbols]", "comma-separated tickers", "AAPL")
  .option("--json", "machine-readable report")
  .action(async (symbolInput: string, opts: { json?: boolean }) => {
    const symbols = parseSymbols(symbolInput);
    if (symbols.length === 0) {
      fail("no valid symbols given");
      process.exit(1);
    }
    const rt = boot(program.opts().mode ? { mode: program.opts().mode } : {});
    if (!opts.json) banner();

    const report = await rt.engine.scan(symbols, rt.source, opts.json ? undefined : streamEvent);

    if (opts.json) {
      console.log(JSON.stringify(report, null, 2));
      rt.close();
      return;
    }

    console.log(c.dim(`\n  reasoner: ${report.reasoner}   mode: ${report.mode}   data: ${rt.source.name}\n`));

    heading("Decisions");
    table(
      ["symbol", "action", "conf", "gate", "thesis"],
      report.decisions.map((d, i) => {
        const v = report.verdicts[i];
        const colour = d.action === "buy" ? c.green : d.action === "sell" ? c.red : c.dim;
        return [
          d.symbol,
          colour(d.action.toUpperCase()),
          d.confidence.toFixed(2),
          v?.allowed ? c.green("pass") : c.red(v?.reasons[0]?.slice(0, 34) ?? "blocked"),
          c.dim(d.thesis.slice(0, 58)),
        ];
      }),
    );
    console.log(c.dim(`\n  scan is read-only. run ${c.bold("coral trade")} to place gated paper orders.\n`));
    rt.close();
  });

// ── trade ─────────────────────────────────────────────────────────────────

program
  .command("trade")
  .description("full gated pass: observe → recall → reason → risk → settle → execute")
  .argument("[symbols]", "comma-separated tickers", "AAPL")
  .option("--budget <usd>", "total USD this pass may deploy", "250")
  .option("--max-orders <n>", "hard cap on orders", "3")
  .option("--json", "machine-readable report")
  .option("--yes", "skip the interactive confirmation")
  .action(async (symbolInput: string, opts: { budget: string; maxOrders: string; json?: boolean; yes?: boolean }) => {
    const symbols = parseSymbols(symbolInput);
    if (symbols.length === 0) {
      fail("no valid symbols given");
      process.exit(1);
    }
    const budget = Number(opts.budget);
    const maxOrders = Number(opts.maxOrders);
    if (!Number.isFinite(budget) || budget <= 0) {
      fail("--budget must be a positive number");
      process.exit(1);
    }

    const rt = boot(program.opts().mode ? { mode: program.opts().mode } : {});
    if (!opts.json) {
      banner();
      const live = rt.config.mode === "live";
      console.log(
        `  ${live ? c.red(c.bold("LIVE MODE")) : c.teal(c.bold("PAPER MODE"))}  ·  ` +
          `budget $${budget}  ·  max ${maxOrders} order(s)  ·  ${symbols.join(", ")}\n`,
      );
      if (live && !opts.yes) {
        warn("live orders are real. re-run with --yes if you are sure, or unset CORAL_MODE.");
        rt.close();
        process.exit(1);
      }
    }

    const report = await rt.engine.run({
      symbols,
      source: rt.source,
      budgetUsd: budget,
      maxOrders,
      ...(opts.json ? {} : { onEvent: streamEvent }),
    });

    if (opts.json) {
      console.log(JSON.stringify(report, null, 2));
      rt.close();
      return;
    }

    heading("Pass summary");
    const fills = report.executions.filter((e) => e.status === "filled");
    const rejects = report.executions.filter((e) => e.status === "rejected");
    keyValue([
      ["run", report.runId.slice(0, 8)],
      ["reasoner", report.reasoner],
      ["decisions", report.decisions.length],
      ["fills", fills.length ? c.green(String(fills.length)) : c.dim("0")],
      ["rejected", rejects.length ? c.amber(String(rejects.length)) : c.dim("0")],
      ["polyps grown", c.teal(String(report.polyps.length))],
      ["settled", String(report.settled.length)],
      ["deployed now", `$${rt.memory.deployedCapital().toFixed(2)} / $${rt.risk.limits.maxDeployedUsd}`],
    ]);

    if (fills.length) {
      heading("Fills");
      table(
        ["symbol", "side", "notional", "qty", "price"],
        fills.map((f) => [f.symbol, f.action.toUpperCase(), `$${f.notional.toFixed(2)}`, f.qty.toFixed(4), `$${f.price.toFixed(2)}`]),
      );
    }
    if (rejects.length) {
      heading("Rejected by the risk manager");
      for (const r of rejects) console.log(`  ${c.red("✗")} ${r.symbol} ${r.action}: ${c.dim(r.reasons.join("; "))}`);
    }

    if (report.polyps.length) {
      heading("Polyps grown this pass");
      for (const p of report.polyps) {
        console.log(`  ${c.dim("•")} ${c.bold(p.kind.padEnd(10))} ${p.symbol ?? "reef"} ${c.dim(p.thesis.slice(0, 70))}`);
      }
    }
    console.log();
    rt.close();
  });

// ── evolve ────────────────────────────────────────────────────────────────

program
  .command("evolve")
  .description("advance a generation: promote what works, demote what does not")
  .option("--dry-run", "show the verdict without writing a generation record")
  .option("--min-samples <n>", "polyps needed before a zone is judged", "3")
  .action((opts: { dryRun?: boolean; minSamples: string }) => {
    const rt = boot();
    banner();
    const result = evolve(rt.memory, {
      ...(opts.dryRun ? { dryRun: true } : {}),
      minSamples: Number(opts.minSamples),
    });
    rt.router.syncZones(rt.memory.zones());

    heading(opts.dryRun ? "Evolution (dry run)" : `Evolution · generation ${result.generation}`);
    const list = (label: string, items: string[], colour: (s: string) => string) => {
      console.log(`  ${label.padEnd(10)} ${items.length ? colour(items.join(", ")) : c.dim("—")}`);
    };
    list("promoted", result.promoted, c.green);
    list("demoted", result.demoted, c.amber);
    list("retired", result.retired, c.red);

    if (result.notes.length) {
      heading("Notes");
      for (const n of result.notes) console.log(`  ${c.dim("·")} ${n}`);
    }

    if (result.evolution) {
      console.log(`\n  ${c.teal("✓")} ${result.evolution.summary}\n`);
    } else {
      console.log(`\n  ${c.dim("dry run — nothing written. drop --dry-run to advance the generation.")}\n`);
    }
    rt.close();
  });

// ── history ───────────────────────────────────────────────────────────────

program
  .command("history")
  .description("trade ledger and settled polyps")
  .option("-n, --limit <n>", "rows to show", "15")
  .option("--json", "machine-readable output")
  .action((opts: { limit: string; json?: boolean }) => {
    const rt = boot();
    const limit = Number(opts.limit);
    const ledger = rt.memory.ledger(limit);
    const evolutions = rt.memory.evolutions(5);

    if (opts.json) {
      console.log(JSON.stringify({ ledger, evolutions }, null, 2));
      rt.close();
      return;
    }

    banner();
    heading("Ledger");
    table(
      ["when", "mode", "symbol", "side", "notional", "qty", "price", "status"],
      ledger.map((l) => [
        formatDistanceToNow(new Date(l.ts), { addSuffix: true }),
        l.mode,
        l.symbol,
        l.side.toUpperCase(),
        `$${l.notional.toFixed(2)}`,
        l.qty.toFixed(4),
        `$${l.price.toFixed(2)}`,
        l.status === "filled" ? c.green("filled") : l.status === "rejected" ? c.red("rejected") : c.dim(l.status),
      ]),
    );

    heading("Generations");
    if (evolutions.length === 0) {
      console.log(c.dim("  no generations yet — run `coral evolve` once there are a few polyps"));
    } else {
      for (const e of evolutions) {
        console.log(`  ${c.teal("gen " + e.generation)} ${c.dim(formatDistanceToNow(new Date(e.ts), { addSuffix: true }))}`);
        console.log(`         ${e.summary}`);
      }
    }
    console.log();
    rt.close();
  });

// ── reef ──────────────────────────────────────────────────────────────────

program
  .command("reef")
  .description("read the reef: recent polyps, or recall against a query")
  .argument("[query]", "what to recall, e.g. 'AAPL oversold bounce'")
  .option("-n, --limit <n>", "polyps to show", "12")
  .option("--why", "explain why each polyp matched")
  .option("--json", "machine-readable output")
  .action((query: string | undefined, opts: { limit: string; why?: boolean; json?: boolean }) => {
    const rt = boot();
    const limit = Number(opts.limit);
    const scored = query
      ? rt.memory.recall({ query, limit })
      : rt.memory.latest(limit).map((p) => ({ polyp: p, score: 1, why: "most recent" }));

    if (opts.json) {
      console.log(JSON.stringify(scored.map((s) => ({ ...s.polyp, score: s.score, why: s.why })), null, 2));
      rt.close();
      return;
    }

    banner();
    heading(query ? `Recall · "${query}"` : "Most recent polyps");
    if (scored.length === 0) {
      console.log(c.dim("  the reef is empty. run `coral trade` to grow the first polyp."));
      rt.close();
      return;
    }
    table(
      ["when", "kind", "symbol", "action", "conf", "outcome", "pnl", "thesis"],
      scored.map((s) => [
        formatDistanceToNow(new Date(s.polyp.createdAt), { addSuffix: true }),
        s.polyp.kind,
        s.polyp.symbol ?? "—",
        s.polyp.action.toUpperCase(),
        s.polyp.confidence.toFixed(2),
        s.polyp.outcome === "win" ? c.green("win") : s.polyp.outcome === "loss" ? c.red("loss") : c.dim(s.polyp.outcome),
        s.polyp.pnl === 0 ? c.dim("—") : s.polyp.pnl > 0 ? c.green(`$${s.polyp.pnl.toFixed(2)}`) : c.red(`$${s.polyp.pnl.toFixed(2)}`),
        c.dim(s.polyp.thesis.slice(0, 44)),
      ]),
    );
    if (opts.why && query) {
      heading("Why these matched");
      for (const s of scored) console.log(`  ${c.dim("•")} ${s.polyp.id.slice(0, 8)}  ${c.dim(s.why)}`);
    }
    console.log();
    rt.close();
  });

// ── serve ─────────────────────────────────────────────────────────────────

program
  .command("serve")
  .description("run CORAL as an MCP server on stdio (for Claude Code, Codex, Cursor, Gemini, Grok)")
  .action(async () => {
    // Nothing may be printed on stdout before the transport starts.
    process.stderr.write("CORAL MCP server starting…\n");
    await serveCoral();
  });

// ── agents ────────────────────────────────────────────────────────────────

program
  .command("agents")
  .description("list the AI agent hosts CORAL can plug into, and what each supports")
  .action(() => {
    banner();
    heading("Supported agent hosts");
    const detected = detect();
    table(
      ["host", "config", "detected", "note"],
      HOSTS.map((h) => {
        const d = detected.find((x) => x.host.id === h.id);
        return [h.id, c.dim(h.configPath().replace(process.env.HOME ?? "", "~")), d?.exists ? c.green("yes") : c.dim("no"), c.dim((h.note ?? "").slice(0, 44))];
      }),
    );
    console.log(`\n  ${c.dim("CORAL speaks MCP in both directions: it calls the Robinhood Trading MCP, and it serves itself to your agent.")}\n`);
  });

program.parseAsync(process.argv).catch((err: unknown) => {
  fail((err as Error).message);
  if (process.env.CORAL_DEBUG) console.error(err);
  process.exit(1);
});
